// עיצוב סכומי כסף לתצוגה - מקור אמת יחיד לכל המסכים.
//
// למה זה קיים: סכומים מסוימים נשמרים ב-DB ברזולוציית אגורות (הוצאת המס
// האוטומטית = 10% מתקבול, למשל 787.5 מתוך 7,875). דפי הדוחות עיגלו אותם
// לתצוגה ודפים אחרים הדפיסו toLocaleString גולמי - כך שאותה שורת מס הופיעה
// כ-₪788 בדוח המס וכ-₪787.5 במסך ההוצאות. הנתון ב-DB נשאר מדויק; רק התצוגה
// מעוגלת, ובאותה צורה בכל מקום.

/** מספר מעוגל עם מפרידי אלפים, בלי סימן מטבע. */
export function formatAmount(n: number): string {
  return Math.round(n).toLocaleString("he-IL");
}

/** סכום מעוגל עם ₪ - הצורה הנפוצה בממשק. */
export function formatCurrency(n: number): string {
  return `₪${formatAmount(n)}`;
}
